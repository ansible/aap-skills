#!/usr/bin/env python3
"""
Sync shared content into the skills that use it.

A skill is served over MCP as a closed set of files: SEP-2640 requires every
resource a skill publishes to resolve inside that skill's own directory, and
the MCP server builds its catalog from exactly the files it finds there. A
file at the repository root therefore has no URI at all — it is not merely
hard to reach, it is not served. Symlinking does not help either: the SDK's
filesystem adapter reports a symlink as an unsupported entry and the catalog
drops the entire skill that contains it.

So shared content has to be duplicated into each skill that uses it, and the
duplication has to be mechanical rather than manual. The repository-root file
is the single source of truth; the copy inside a skill is generated. A skill
opts in by having the destination file — this script then keeps it identical,
and `--check` fails CI if it is not.

Usage:
    python3 scripts/sync_shared.py            # write the copies
    python3 scripts/sync_shared.py --check    # fail if any copy is stale
"""

import argparse
import sys
from pathlib import Path
from typing import List, Tuple

# Repository-relative source -> skill-relative destination.
#
# The destination always sits under 'context/' so that a reader can tell a
# synced copy from material the skill wrote itself, which lives in
# 'references/'. Nothing under a skill's 'context/' should be edited by hand.
SHARED_CONTENT = {
    'context/output-format.md': 'context/output-format.md',
    'docs/content-type-definition.md': 'context/content-type-definition.md',
}

GENERATED_BANNER = (
    '<!-- Generated by scripts/sync_shared.py from {source}. Do not edit. -->\n'
)


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def expected_content(source: Path, source_rel: str) -> str:
    """What the copy must contain: the source, with a provenance banner.

    The banner goes after the front matter rather than before it, because the
    server's reader requires SKILL.md-style front matter to start on line 1
    and a shared file may carry its own.
    """
    text = source.read_text(encoding='utf-8')
    banner = GENERATED_BANNER.format(source=source_rel)

    if text.startswith('---\n'):
        parts = text.split('---\n', 2)
        if len(parts) == 3:
            return f"---\n{parts[1]}---\n{banner}{parts[2]}"
    return banner + text


def planned_copies(root: Path) -> List[Tuple[Path, Path, str]]:
    """Every (source, destination, source_rel) a skill has opted in to.

    Opting in is having the destination file. That keeps the declaration in
    one place — the skill directory, which is also what the server serves —
    instead of a manifest that can disagree with what is on disk.
    """
    skills_dir = root / 'skills'
    if not skills_dir.is_dir():
        return []

    copies = []
    for skill_dir in sorted(skills_dir.iterdir()):
        if not (skill_dir / 'SKILL.md').is_file():
            continue
        for source_rel, dest_rel in sorted(SHARED_CONTENT.items()):
            destination = skill_dir / dest_rel
            if destination.is_file():
                copies.append((root / source_rel, destination, source_rel))
    return copies


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='report stale copies instead of writing them')
    args = parser.parse_args()

    root = repo_root()
    copies = planned_copies(root)

    if not copies:
        print('No skill has opted in to shared content.')
        return 0

    stale = []
    written = []
    for source, destination, source_rel in copies:
        shown = destination.relative_to(root)
        if not source.is_file():
            print(f"✗ {shown}: source {source_rel} does not exist")
            stale.append(shown)
            continue

        wanted = expected_content(source, source_rel)
        if destination.read_text(encoding='utf-8') == wanted:
            continue

        if args.check:
            print(f"✗ {shown} differs from {source_rel}")
            stale.append(shown)
        else:
            destination.write_text(wanted, encoding='utf-8')
            written.append(shown)

    if args.check:
        if stale:
            print(f"\n❌ {len(stale)} stale cop(ies). "
                  f"Run: python3 scripts/sync_shared.py")
            return 1
        print(f"✅ {len(copies)} shared cop(ies) are up to date.")
        return 0

    for shown in written:
        print(f"↻ {shown}")
    print(f"✅ {len(copies)} shared cop(ies) in sync "
          f"({len(written)} updated).")
    return 0


if __name__ == '__main__':
    sys.exit(main())
